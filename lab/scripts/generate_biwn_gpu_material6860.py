"""Coordinator build-time recompilation of three complete material code ranges.

No local-model authorship or acceptance claim; preserve header-sized originals.
"""
import hashlib,json,re
from pathlib import Path
import generate_biwn_gpu_geometry as base
import package_gpu6380_candidate as engine
ROOT=base.ROOT
def main():
    session=Path(json.loads((ROOT/'projects/black-ice-white-noise/analysis/current-session.json').read_text())['directory'])
    out=session/'gpu-material6860-candidate';out.mkdir(exist_ok=True)
    for header,end in [(0x6860,0xf0335a)]:
        name=f'material{header:x}';upper=name.upper();mapping=json.loads((session/f'gpu-render-{header:x}-overlay/initial-linear-decode.json').read_text());rows=[r for r in mapping['rows']if r['address']<end]
        def rename(text):return text.replace('consumer6380',name).replace('CONSUMER6380',upper)
        h=rename(engine.HEADER)
        h=h.replace(' int (*read16)', ' int (*read8)(void *,uint32_t,uint8_t *);\n int (*read16)')
        h=h.replace(' int (*write32)', ' int (*write16)(void *,uint32_t,uint16_t);\n int (*write32)')
        a=h.index('/* Fixed original');b=h.index('enum biwn_gpu_',a)
        h=h[:a]+f'/* Fixed original{header:x} material program, bank0 entry F03240.\n * Caller supplies inherited register/flag and complete memory/control state.\n * Stops at resident F03440 after mandatory delay, without running resident.\n * Errors preserve input state but retain prior external stores. Finite valid\n * source descriptors/buffers required. No opcode decoding or core execution. */\n'+h[b:]
        prefix=rename(engine.PREFIX).replace('local case authorship in manifest','material cases generated by coordinator')
        insert='''static int local(uint32_t a){return a>=0xf03000u&&a<=0xf03fffu;}
static int loadb(struct biwn_gpu_NAME_bus *bus,uint32_t a,uint32_t *v){uint8_t b;if(local(a))return rd32(bus,a&~3u,v);if(bus->read8(bus->context,a,&b))return 2;*v=b;return 0;}
static int wr16(struct biwn_gpu_NAME_bus *bus,uint32_t a,uint32_t v){if(local(a))return wr32(bus,a&~1u,v&0xffffu);return bus->write16(bus->context,a,(uint16_t)v)?2:0;}
'''.replace('NAME',name)
        if header==0x6460:insert='\n'.join(line for line in insert.splitlines()if not line.startswith('static int loadb'))+'\n'
        prefix=prefix.replace('#define CHECK',insert+'#define CHECK')
        prefix=prefix.replace('!bus->read16||!bus->read32||!bus->write32', '!bus->read8||!bus->read16||!bus->read32||!bus->write16||!bus->write32')
        cases=[]
        for row in rows:
            word=int(row['bytes'][:4],16);op=word>>10;m=(word>>5)&31;n=word&31
            if op==39:
                emitted=f'case {hex(row["address"])}u: /* {row["assembly"]} */\n CHECK(loadb(bus,s.registers[0][{m}],&v));s.registers[0][{n}]=v;s.pc={hex(row["address"]+row["size"])}u;break;'
            else:
                emitted=base.emit(row).replace('loadw(bus,&s,','loadw(bus,').replace('rd32(bus,&s,','rd32(bus,').replace('wr32(bus,&s,','wr32(bus,').replace('wr16(bus,&s,','wr16(bus,')
            cases.append(emitted)
        suffix=rename(engine.SUFFIX).replace('s.pc==0xf031beu||s.pc==0xf03440u||s.pc==0xf03ca0u','s.pc==0xf03440u')
        (out/f'biwn_gpu_{name}.h').write_text(h);(out/f'biwn_gpu_{name}.c').write_text(prefix+'\n'.join(cases)+'\n'+suffix)
        report=dict(status='generated_unverified',CPU_header=hex(header),source_instruction_count=len(rows),source_interval=['0xf03240',hex(end)],payload_sha256=mapping['payload_SHA256'],source_sha256={f'biwn_gpu_{name}.{ext}':hashlib.sha256((out/f'biwn_gpu_{name}.{ext}').read_bytes()).hexdigest()for ext in ['c','h']},generator_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),coordinator_authored=True,local_model_case_bodies=False,instructions_decoded=rows,full_renderer_C=False)
        (out/f'{name}-generation.json').write_text(json.dumps(report,indent=2)+'\n');print(json.dumps({k:v for k,v in report.items()if k!='instructions_decoded'}))
if __name__=='__main__':main()
