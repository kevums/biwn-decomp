"""Bind the actual native keyboard run, immutable runtime files and launchers."""
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parents[1]
RT = Path.home() / '.lmstudio/local-ai-lab/native-preview-v1'
def read(p): return json.loads(Path(p).read_text())
def sha(p):
    with Path(p).open('rb') as f: return hashlib.file_digest(f, 'sha256').hexdigest()
def save(p, x): Path(p).write_text(json.dumps(x, indent=2) + '\n')

def main():
    now = datetime.now(timezone.utc)
    out = ROOT / 'verification/native-keyboard-delivery' / now.strftime('%Y%m%dT%H%M%S.%fZ')
    out.mkdir(parents=True)
    protocol = RT / 'runs/native-keyboard-preview-20261020T054856.630533Z/protocol.json'
    run = read(protocol)
    assert run['status'] == 'terminal_native_keyboard_frontend_stopped_pending_review'
    assert run['frames'] == 2528 and run['keyboard_events'] == 11
    assert run['native_coordinate_entries'] == run['native_coordinate_returns'] == 2444
    assert run['all_GPU_Deck_guards_pass'] and run['immutable_native_code_unchanged']
    assert run['original_coordinate_body_steps'] == run['invalid_task_identities'] == 0
    for p, digest in run['source_sha256'].items(): assert sha(p) == digest, p
    rows = read(Path(run['directory']) / 'frames.json')
    assert len(rows) == 2528 and rows[-1]['native_coordinate_returns'] == 2444
    assert any(any(r['movie_flags']) for r in rows) and not any(rows[-1]['movie_flags'])
    app = Path.home() / 'Applications/BIWN Native Preview.app'
    assert (Path.home() / 'Desktop/BIWN Native Preview.app').resolve() == app
    assert (Path.home() / 'Desktop/Local AI Lab Launcher.command').resolve() == ROOT / 'Open Local AI Lab v7.command'
    # Exclude mutable run pointers and interpreter-generated bytecode.
    immutable = {str(p.relative_to(RT)): sha(p) for p in RT.rglob('*')
        if p.is_file() and not {'runs', '__pycache__'} & set(p.relative_to(RT).parts)
        and p.name not in ['manifest.json', 'native-keyboard-preview-current.json']}
    files = ['scripts/run_biwn_native_keyboard_v1.py', 'scripts/native_preview_observer_v1.c',
        'scripts/native_preview_app_launcher_v2.c', 'scripts/package_native_keyboard_v1.py',
        'scripts/review_native_keyboard_delivery_v1.py', 'Play BIWN Native Preview.command',
        'Open Local AI Lab v7.command', 'BIWN Native Preview - Start Here.txt']
    hashes = {str(ROOT / p): sha(ROOT / p) for p in files}
    hashes.update({str(p): sha(p) for p in app.rglob('*') if p.is_file()})
    for p in files:
        dst = out / 'sources' / p; dst.parent.mkdir(parents=True, exist_ok=True); shutil.copy2(ROOT / p, dst)
    shutil.copy2(protocol, out / 'actual-native-GUI-protocol.json')
    review = dict(status='terminal_native_keyboard_GUI_and_shortcuts_reviewed', recorded_at=now.isoformat(),
        directory=str(out), actual_UI_actions='Prior genuine CUA keyboard run: P, 1, D; Deck visibly rendered; 0; P; Escape. Not a scripted-input GUI claim.',
        protocol=str(protocol), protocol_sha256=sha(protocol), frames=2528, native_coordinate_entries=2444,
        native_coordinate_returns=2444, guards_and_immutable_code_pass=True,
        checkpoint_origin=run['checkpoint'], restoration_changes_original_behavior=True,
        emulator='Retained original emulator executing mixed original and compiled68000 game code',
        audio_sink_opened=True, audio_nonzero_samples=run['audio_callbacks']['nonzero_samples'],
        audible_game_audio_verified=False, app=str(app), menu_option=12,
        runtime_immutable_files=immutable, launcher_and_source_sha256=hashes,
        new_model_predictions=0, new_optimizer_updates=0, whole_game_complete=False,
        physical_console_verified=False, future_hardware_verified=False,
        scope='Keyboard frontend delivery and recorded native GUI test only; adds no recovered game routine. Remaining five native Deck callers, IRQ/reentrancy, complete source rebuild and audio/physical acceptance remain incomplete.')
    save(out / 'review.json', review)
    save(ROOT / 'verification/native-keyboard-delivery-current.json', review)
    print(out, flush=True)

if __name__ == '__main__': main()
